-- ========================================
-- 代码相似度结果表 (PostgreSQL)
-- 存储两两代码相似度比对结果
-- ========================================

CREATE TABLE IF NOT EXISTS code_similarity_result (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    competition_id BIGINT NOT NULL,
    problem_index VARCHAR(10) NOT NULL,
    user_uuid_1 BIGINT NOT NULL,
    user_uuid_2 BIGINT NOT NULL,
    source_code_1 TEXT NOT NULL,
    source_code_2 TEXT NOT NULL,
    similarity_score DOUBLE PRECISION NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 添加字段注释
COMMENT ON TABLE code_similarity_result IS '代码相似度结果表,存储两两代码相似度比对结果';
COMMENT ON COLUMN code_similarity_result.id IS '主键ID';
COMMENT ON COLUMN code_similarity_result.competition_id IS '竞赛ID';
COMMENT ON COLUMN code_similarity_result.problem_index IS '题目索引(A,B,C...)';
COMMENT ON COLUMN code_similarity_result.user_uuid_1 IS '用户1的UUID';
COMMENT ON COLUMN code_similarity_result.user_uuid_2 IS '用户2的UUID';
COMMENT ON COLUMN code_similarity_result.source_code_1 IS '用户1的源代码';
COMMENT ON COLUMN code_similarity_result.source_code_2 IS '用户2的源代码';
COMMENT ON COLUMN code_similarity_result.similarity_score IS '相似度分数(0-1)';
COMMENT ON COLUMN code_similarity_result.created_at IS '创建时间';

-- 索引优化
CREATE INDEX IF NOT EXISTS idx_similarity_competition_problem ON code_similarity_result(competition_id, problem_index);
CREATE INDEX IF NOT EXISTS idx_similarity_score ON code_similarity_result(similarity_score DESC);
CREATE INDEX IF NOT EXISTS idx_similarity_users ON code_similarity_result(user_uuid_1, user_uuid_2);

-- ========================================
-- 说明:
-- 1. 只存储相似度超过阈值(如0.85)的记录,减少数据量
-- 2. user_uuid_1 < user_uuid_2,避免重复存储(A-B和B-A)
-- 3. similarity_score 范围 0-1,越接近1越相似
-- 4. source_code_1 和 source_code_2 存储具体代码,方便直接查询展示
-- ========================================
